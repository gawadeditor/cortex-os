# Public API — get_failure_summary
# ---------------------------------------------------------------------------

def get_failure_summary(
    db_path:    Optional[Path] = None,
    episode_id: Optional[str]  = None,
    limit:      int            = 10,
) -> list[FailureRecord]:
    """
    Return the top failure patterns across all asset generation attempts.

    Groups by (error_type, asset_type, provider) and sorts by frequency.

    Non-blocking: returns [] on any exception.

    Args:
        db_path:    Override SQLite path.
        episode_id: Restrict to one episode if provided.
        limit:      Maximum records to return. Default 10.

    Returns:
        List of FailureRecord sorted descending by count.
    """
    try:
        clauses = ["status='failed'", "error_type IS NOT NULL"]
        params: list = []
        if episode_id:
            clauses.append("episode_id=?")
            params.append(episode_id)
        where = " AND ".join(clauses)

        conn = get_connection(_resolve_db_path(db_path))
        try:
            rows = conn.execute(
                f"""
                SELECT error_type, asset_type, provider, COUNT(*) AS cnt
                FROM asset_versions
                WHERE {where}
                GROUP BY error_type, asset_type, provider
                ORDER BY cnt DESC
                LIMIT ?
                """,
                params + [limit],
            ).fetchall()
        finally:
            conn.close()

        return [
            FailureRecord(
                error_type = row["error_type"],
                count      = row["cnt"],
                asset_type = row["asset_type"],
                provider   = row["provider"],
            )
            for row in rows
        ]
    except Exception:
        return []


