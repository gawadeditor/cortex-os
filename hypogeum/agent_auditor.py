def run_health_summary(
    db_path:    Optional[Path] = None,
    episode_id: Optional[str]  = None,
) -> RunHealthSummary:
    """
    Return high-level run completion statistics.

    Non-blocking: returns an all-zero RunHealthSummary on any exception.

    Args:
        db_path:    Override SQLite path.
        episode_id: Restrict to one episode if provided.

    Returns:
        RunHealthSummary with aggregated run metrics.
    """
    _empty = RunHealthSummary(
        total_runs=0, completed=0, failed=0, in_progress=0,
        completion_rate=0.0, avg_duration_ms=None, total_cost_usd=0.0,
    )
    try:
        ep_clause, ep_params = _episode_clause(episode_id)
        conn = get_connection(_resolve_db_path(db_path))
        try:
            row = conn.execute(
                f"""
                SELECT
                    COUNT(*)                                                    AS total,
                    SUM(CASE WHEN status='complete'  THEN 1 ELSE 0 END)        AS completed,
                    SUM(CASE WHEN status='failed'    THEN 1 ELSE 0 END)        AS failed,
                    SUM(CASE WHEN status='running'   THEN 1 ELSE 0 END)        AS in_progress,
                    AVG(duration_ms)                                            AS avg_dur,
                    COALESCE(SUM(total_cost_usd), 0)                           AS total_cost
                FROM runs
                WHERE 1=1{ep_clause}
                """,
                ep_params,
            ).fetchone()
        finally:
            conn.close()

        total    = row["total"]    or 0
        completed = row["completed"] or 0
        return RunHealthSummary(
            total_runs       = total,
            completed        = completed,
            failed           = row["failed"]     or 0,
            in_progress      = row["in_progress"] or 0,
            completion_rate  = _safe_rate(completed, total),
            avg_duration_ms  = row["avg_dur"],
            total_cost_usd   = float(row["total_cost"] or 0),
        )
    except Exception:
        return _empty


# ---------------------------------------------------------------------------
# Public API — audit_agents (full report)
# ---------------------------------------------------------------------------

def audit_agents(
    db_path:    Optional[Path] = None,
    episode_id: Optional[str]  = None,
    limit_runs: int            = 50,
) -> AgentAuditReport:
    """
    Generate a comprehensive agent performance audit report.

    Aggregates all sub-reports (stages, gates, assets, failures, run health)
    into one AgentAuditReport. Non-blocking: partial results are returned if
    any sub-query fails.

    Args:
        db_path:    Override SQLite path.
        episode_id: Restrict to one episode if provided.
        limit_runs: Informational only; currently unused for SQL LIMIT.
                    Reserved for future windowed analysis.

    Returns:
        AgentAuditReport with generated_at timestamp and all sub-reports.
    """
    # Collect all stage names
    stage_names: list[str] = []
    try:
        ep_clause, ep_params = _episode_clause(episode_id)
        conn = get_connection(_resolve_db_path(db_path))
        try:
            rows = conn.execute(
                f"SELECT DISTINCT stage_name FROM stage_executions WHERE 1=1{ep_clause}",
                ep_params,
            ).fetchall()
        finally:
            conn.close()
        stage_names = [r["stage_name"] for r in rows]
    except Exception:
        pass

    stages = []
    for sn in sorted(stage_names):
        result = audit_stage(sn, db_path=db_path, episode_id=episode_id)
        if result:
            stages.append(result)

    health = run_health_summary(db_path=db_path, episode_id=episode_id)

    return AgentAuditReport(
        generated_at = datetime.now(timezone.utc).isoformat(),
        run_count    = health.total_runs,
        stages       = stages,
        gates        = audit_gates(db_path=db_path, episode_id=episode_id),
        assets       = audit_asset_generation(db_path=db_path, episode_id=episode_id),
        top_failures = get_failure_summary(db_path=db_path, episode_id=episode_id),
        run_health   = health,
    )
