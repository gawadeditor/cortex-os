"""
hypogeum/agent_auditor.py — Agent Performance Auditor

Read-only analysis of pipeline agent performance using the operational DB.
Produces structured audit reports from stage_executions, gate_verdicts,
asset_versions, costs, and runs tables.

Architecture:
    All functions are read-only (no writes). Non-blocking: any exception
    returns empty/None rather than propagating.

    Data sources:
        stage_executions — per-stage timing, status, cost
        gate_verdicts    — brand/QA gate pass and block rates
        asset_versions   — generation retry rates and failure analysis
        runs             — overall pipeline run health
        costs            — cost attribution per provider/stage

Public API:
    audit_agents(
        db_path=None, episode_id=None, limit_runs=50,
    ) -> AgentAuditReport

    audit_stage(
        stage_name, db_path=None, episode_id=None,
    ) -> StageAuditResult | None

    audit_gates(
        db_path=None, episode_id=None,
    ) -> list[GateAuditResult]

    audit_asset_generation(
        asset_type=None, db_path=None, episode_id=None,
    ) -> list[AssetAuditResult]

    get_failure_summary(
        db_path=None, episode_id=None, limit=10,
    ) -> list[FailureRecord]

    run_health_summary(
        db_path=None, episode_id=None,
    ) -> RunHealthSummary
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional

from hypogeum.db import get_connection


# ---------------------------------------------------------------------------
# Default path
# ---------------------------------------------------------------------------

_PROJECT_ROOT = Path(__file__).resolve().parent.parent
_DEFAULT_DB_PATH = _PROJECT_ROOT / ".hypogeum-assets" / "hypogeum.db"


# ---------------------------------------------------------------------------
# Result dataclasses
# ---------------------------------------------------------------------------

@dataclass
class StageAuditResult:
    """Performance metrics for one pipeline stage across all runs."""
    stage_name:       str
    total_executions: int
    successes:        int
    failures:         int
    skips:            int
    success_rate:     float          # successes / (total - skips), or 0.0
    avg_duration_ms:  Optional[float]
    avg_cost_usd:     Optional[float]
    total_cost_usd:   float


@dataclass
class GateAuditResult:
    """Pass/block/warning rates for one pipeline gate."""
    gate_name:        str
    total_evaluations: int
    passes:           int
    blocks:           int
    warnings:         int
    pass_rate:        float          # passes / total, or 0.0
    block_rate:       float          # blocks / total, or 0.0


@dataclass
class AssetAuditResult:
    """Generation attempt metrics for one asset_type + provider combination."""
    asset_type:              str
    provider:                str
    total_attempts:          int
    first_attempt_successes: int
    retries:                 int
    failures:                int
    successes:               int
    success_rate:            float   # successes / total_attempts, or 0.0
    retry_rate:              float   # retries / total_attempts, or 0.0
    avg_cost_per_success:    Optional[float]
    most_common_error:       Optional[str]


@dataclass
class FailureRecord:
    """One failure pattern observed across asset generation attempts."""
    error_type: str
    count:      int
    asset_type: str
    provider:   str


@dataclass
class RunHealthSummary:
    """High-level run completion statistics."""
    total_runs:       int
    completed:        int
    failed:           int
    in_progress:      int
    completion_rate:  float           # completed / total, or 0.0
    avg_duration_ms:  Optional[float]
    total_cost_usd:   float


@dataclass
class AgentAuditReport:
    """
    Comprehensive factory agent performance report.

    Generated by audit_agents(). Aggregates all sub-reports into one
    structure suitable for display or persistence.
    """
    generated_at:    str
    run_count:       int
    stages:          list[StageAuditResult]   = field(default_factory=list)
    gates:           list[GateAuditResult]    = field(default_factory=list)
    assets:          list[AssetAuditResult]   = field(default_factory=list)
    top_failures:    list[FailureRecord]      = field(default_factory=list)
    run_health:      Optional[RunHealthSummary] = None


# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------

def _resolve_db_path(db_path: Optional[Path]) -> Path:
    return Path(db_path) if db_path is not None else _DEFAULT_DB_PATH


def _safe_rate(numerator: int, denominator: int) -> float:
    """Return numerator/denominator or 0.0 if denominator is zero."""
    return numerator / denominator if denominator > 0 else 0.0


def _episode_clause(episode_id: Optional[str], table_alias: str = "") -> tuple[str, list]:
    """Build an episode_id WHERE/AND clause if provided."""
    prefix = f"{table_alias}." if table_alias else ""
    if episode_id:
        return f" AND {prefix}episode_id = ?", [episode_id]
    return "", []


# ---------------------------------------------------------------------------
# Public API — audit_stage
# ---------------------------------------------------------------------------

def audit_stage(
    stage_name: str,
    db_path:    Optional[Path] = None,
    episode_id: Optional[str]  = None,
) -> Optional[StageAuditResult]:
    """
    Return performance metrics for a single named pipeline stage.

    Returns None if the stage has no records or on any exception.

    Args:
        stage_name: Pipeline stage name (e.g. "visual_package_director").
        db_path:    Override SQLite path.
        episode_id: Restrict analysis to one episode if provided.

    Returns:
        StageAuditResult or None.
    """
    try:
        ep_clause, ep_params = _episode_clause(episode_id)
        conn = get_connection(_resolve_db_path(db_path))
        try:
            row = conn.execute(
                f"""
                SELECT
                    COUNT(*)                                                       AS total,
                    SUM(CASE WHEN status='completed' THEN 1 ELSE 0 END)           AS successes,
                    SUM(CASE WHEN status='failed'    THEN 1 ELSE 0 END)           AS failures,
                    SUM(CASE WHEN skipped=1          THEN 1 ELSE 0 END)           AS skips,
                    AVG(CASE WHEN status='completed' THEN duration_ms END)        AS avg_dur,
                    AVG(cost_usd)                                                  AS avg_cost,
                    COALESCE(SUM(cost_usd), 0)                                    AS total_cost
                FROM stage_executions
                WHERE stage_name = ?{ep_clause}
                """,
                [stage_name] + ep_params,
            ).fetchone()
        finally:
            conn.close()

        total = row["total"] or 0
        if total == 0:
            return None

        successes = row["successes"] or 0
        failures  = row["failures"]  or 0
        skips     = row["skips"]     or 0
        active    = total - skips

        return StageAuditResult(
            stage_name       = stage_name,
            total_executions = total,
            successes        = successes,
            failures         = failures,
            skips            = skips,
            success_rate     = _safe_rate(successes, active),
            avg_duration_ms  = row["avg_dur"],
            avg_cost_usd     = row["avg_cost"],
            total_cost_usd   = float(row["total_cost"] or 0),
        )
    except Exception:
        return None


