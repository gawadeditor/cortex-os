# Public API — audit_gates
# ---------------------------------------------------------------------------

def audit_gates(
    db_path:    Optional[Path] = None,
    episode_id: Optional[str]  = None,
) -> list[GateAuditResult]:
    """
    Return pass/block/warning rates for all pipeline gates.

    Non-blocking: returns [] on any exception.

    Args:
        db_path:    Override SQLite path.
        episode_id: Restrict to one episode if provided.

    Returns:
        List of GateAuditResult, one per gate_name, ordered by gate_name.
    """
    try:
        ep_clause, ep_params = _episode_clause(episode_id)
        conn = get_connection(_resolve_db_path(db_path))
        try:
            rows = conn.execute(
                f"""
                SELECT
                    gate_name,
                    COUNT(*)                                                           AS total,
                    SUM(CASE WHEN verdict IN ('APPROVED','APPROVED_WITH_FLAGS')
                             THEN 1 ELSE 0 END)                                        AS passes,
                    SUM(CASE WHEN verdict IN ('REJECTED','BLOCKED')
                             THEN 1 ELSE 0 END)                                        AS blocks,
                    SUM(CASE WHEN verdict = 'WARNING' THEN 1 ELSE 0 END)               AS warnings
                FROM gate_verdicts
                WHERE 1=1{ep_clause}
                GROUP BY gate_name
                ORDER BY gate_name
                """,
                ep_params,
            ).fetchall()
        finally:
            conn.close()

        results: list[GateAuditResult] = []
        for row in rows:
            total   = row["total"]   or 0
            passes  = row["passes"]  or 0
            blocks  = row["blocks"]  or 0
            warnings = row["warnings"] or 0
            results.append(GateAuditResult(
                gate_name         = row["gate_name"],
                total_evaluations = total,
                passes            = passes,
                blocks            = blocks,
                warnings          = warnings,
                pass_rate         = _safe_rate(passes, total),
                block_rate        = _safe_rate(blocks, total),
            ))
        return results
    except Exception:
        return []


# ---------------------------------------------------------------------------
# Public API — audit_asset_generation
# ---------------------------------------------------------------------------

def audit_asset_generation(
    asset_type: Optional[str]  = None,
    db_path:    Optional[Path] = None,
    episode_id: Optional[str]  = None,
) -> list[AssetAuditResult]:
    """
    Return generation attempt metrics grouped by asset_type + provider.

    Includes success rates, retry rates, cost per success, and the most
    common error type observed for each combination.

    Non-blocking: returns [] on any exception.

    Args:
        asset_type: Filter to one asset type if provided.
        db_path:    Override SQLite path.
        episode_id: Restrict to one episode if provided.

    Returns:
        List of AssetAuditResult ordered by asset_type, provider.
    """
    try:
        clauses = ["1=1"]
        params: list = []
        if asset_type:
            clauses.append("asset_type = ?")
            params.append(asset_type)
        if episode_id:
            clauses.append("episode_id = ?")
            params.append(episode_id)

        where = " AND ".join(clauses)

        conn = get_connection(_resolve_db_path(db_path))
        try:
            rows = conn.execute(
                f"""
                SELECT
                    asset_type,
                    provider,
                    COUNT(*)                                                        AS total,
                    SUM(CASE WHEN attempt_number=1 AND status='succeeded'
                             THEN 1 ELSE 0 END)                                    AS first_successes,
                    SUM(CASE WHEN attempt_number>1 THEN 1 ELSE 0 END)              AS retries,
                    SUM(CASE WHEN status='failed' THEN 1 ELSE 0 END)               AS failures,
                    SUM(CASE WHEN status='succeeded' THEN 1 ELSE 0 END)            AS successes,
                    COALESCE(SUM(CASE WHEN status='succeeded'
                             THEN cost_usd ELSE 0 END), 0)                         AS success_cost
                FROM asset_versions
                WHERE {where}
                GROUP BY asset_type, provider
                ORDER BY asset_type, provider
                """,
                params,
            ).fetchall()
        finally:
            conn.close()

        results: list[AssetAuditResult] = []
        for row in rows:
            total     = row["total"]     or 0
            successes = row["successes"] or 0
            retries   = row["retries"]   or 0
            failures  = row["failures"]  or 0
            first_ok  = row["first_successes"] or 0
            succ_cost = float(row["success_cost"] or 0)
            avg_cost  = (succ_cost / successes) if successes > 0 else None

            # Most common error for this type+provider combo
            top_error = _most_common_error(
                row["asset_type"], row["provider"], episode_id,
                _resolve_db_path(db_path),
            )

            results.append(AssetAuditResult(
                asset_type              = row["asset_type"],
                provider                = row["provider"],
                total_attempts          = total,
                first_attempt_successes = first_ok,
                retries                 = retries,
                failures                = failures,
                successes               = successes,
                success_rate            = _safe_rate(successes, total),
                retry_rate              = _safe_rate(retries, total),
                avg_cost_per_success    = avg_cost,
                most_common_error       = top_error,
            ))
        return results
    except Exception:
        return []


def _most_common_error(
    asset_type: str,
    provider:   str,
    episode_id: Optional[str],
    db_path:    Path,
) -> Optional[str]:
    """Return the most frequent error_type for a given asset/provider combo."""
    try:
        clauses = ["status='failed'", "error_type IS NOT NULL",
                   "asset_type=?", "provider=?"]
        params: list = [asset_type, provider]
        if episode_id:
            clauses.append("episode_id=?")
            params.append(episode_id)
        where = " AND ".join(clauses)
        conn = get_connection(db_path)
        try:
            row = conn.execute(
                f"""
                SELECT error_type, COUNT(*) AS cnt
                FROM asset_versions
                WHERE {where}
                GROUP BY error_type ORDER BY cnt DESC LIMIT 1
                """,
                params,
            ).fetchone()
        finally:
            conn.close()
        return row["error_type"] if row else None
    except Exception:
        return None


