"""
hypogeum/agents/canonical_metadata_agent.py — Generates the real,
per-(deliverable_id, platform) canonical publication metadata package
(hypogeum.publishing.canonical_metadata.CanonicalPlatformMetadata shape)
that hypogeum.publishing.cross_platform_readiness now REQUIRES before any
Zernio submission for every enabled deliverable/platform pair.

Fixed 2026-08-23 (permanent workflow, not a one-off ep_f3619022 repair --
see docs/operations/audits/ZERNIO_CANONICAL_METADATA_CONTRACT_2026-08-23.md):
prior to this module, a canonical_platform_metadata entry could only ever
be created by hand (a human-written repair artifact) -- there was no
automatic path back to a resolved value for a freshly-produced episode,
which is exactly the class of defect that let ep_f3619022 reach Zernio
with every platform-specific field blank. This module closes that gap:
called automatically (see build_publish_package_from_episode_dir()) for
any (deliverable_id, platform) pair missing a canonical entry.

Grounding against fabrication, same discipline as
hypogeum.agents.shorts_metadata: the model is given ONLY that
deliverable's own real script content (narration_beats for a main
episode's sections, or the SAME already-generated, script-grounded
caption hypogeum.agents.shorts_metadata.generate_shorts_captions()
produced for a Short) and that episode's own real, verified Research
Package sources -- it may never introduce a fact, name, date, claim, or
source URL that does not already exist in those real artifacts.

Deterministic fields (chapters, sources, claim_source_map,
source_artifact_ids, input_fingerprint, generated_at/approved_at) are
computed directly from real on-disk artifacts, NEVER generated by the
model -- only title/description/CTA/visible_hashtags/backend_tags/
first_comment are model-generated, and even those are validated
(non-empty, non-placeholder, hashtags as real tokens, distinct per
platform) before being accepted. category_id/ai_disclosure/
platform_policy_fields are channel-policy values (never generated
per-episode) -- supplied by the caller from the channel's own
platform_deliverable_policy, never invented here.

Public API:
    CanonicalMetadataGenerationError
    generate_canonical_platform_metadata_for_deliverable(
        episode_id, episode_dir, deliverable_id, deliverable_class,
        target_platforms, final_render_package, *, config, channel_id=None,
        platform_deliverable_policy=None, llm_call=None) -> List[dict]
"""

from __future__ import annotations

import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Callable, Dict, List, Optional
from urllib.parse import urlparse

from hypogeum.config import Config
from hypogeum.logger import get_logger

_AGENT_NAME = "canonical_metadata_agent"

# Platforms with a documented backend-tags concept (see
# hypogeum.publishing.zernio_platform_contracts) -- never invented for a
# platform whose contract does not define one.
_PLATFORMS_WITH_BACKEND_TAGS = frozenset({"youtube"})
# Platforms with a documented first-comment concept.
_PLATFORMS_WITH_FIRST_COMMENT = frozenset({"youtube"})

_SYSTEM_PROMPT = """You are an SEO/social-editorial assistant producing publication
metadata for a documentary-style video, one deliverable at a time, across the
platforms it will be published to.

You will receive a JSON object with:
  "deliverable_class": "main_episode" or "shorts"
  "grounding_text": the ONLY real content you may draw facts, names, dates, or
      claims from -- this is the actual, already-written narration/caption
      for this exact deliverable. You may summarize, rephrase, and add a CTA
      and hashtags, but you must NEVER introduce a fact, name, date, claim,
      or number that is not already present in grounding_text.
  "sources": a list of {{"title", "url"}} objects -- real, verified sources for
      this episode. You may reference these in a CTA or description, but you
      must NEVER invent a different source or URL.
  "platforms": a list of platform names to produce output for, each with its
      own caption/description character limit and rules:
{platform_rules}

For EACH requested platform, produce:
  "title": a platform-appropriate optimized title (only for platforms where
      title_supported is true below; omit for platforms where it is false).
      Maximum {youtube_title_limit} characters for YouTube.
  "description": the full viewer-facing description/caption for that
      platform, within its documented character limit. Must read as real,
      polished publication copy -- never a bare research summary or a
      logline. For platforms other than the deliverable's primary one,
      adapt tone/length/CTA-placement genuinely for that platform; never
      return byte-identical text across two different platforms.
  "visible_hashtags": a list of hashtags (each starting with '#', no spaces)
      that you have ALSO embedded, as complete tokens, inside "description"
      itself. 3 to 8 hashtags, relevant to the deliverable's actual content.
  "backend_tags": ONLY for platforms where backend_tags_supported is true
      below -- a list of 8 to 17 lowercase search-intent phrases (never
      hashtags, never overlapping with visible_hashtags), each under 100
      characters, combined length under 500 characters. Omit entirely for
      a platform where backend_tags_supported is false.
  "cta": one sentence encouraging engagement (subscribe/comment/share),
      grounded only in this deliverable's own content.
  "first_comment": ONLY for platforms where first_comment_supported is true
      below -- one short, real comment continuing the conversation (a
      question or a pointer to sources). Omit entirely otherwise.

Return ONLY a JSON object of this exact shape:
{{"platforms": {{"<platform_name>": {{"title": "...", "description": "...",
"visible_hashtags": ["#..."], "backend_tags": ["..."], "cta": "...",
"first_comment": "..."}}, ...}}}}
Include an entry for every requested platform. Omit "title"/"backend_tags"/
"first_comment" keys entirely (do not include them as null or empty
string) for a platform whose rules say they are not supported."""


class CanonicalMetadataGenerationError(RuntimeError):
    """
    Raised when a real, grounded canonical metadata package cannot be
    produced for every requested platform. Never caught here to silently
    fall back to a placeholder, generic content, or a research artifact
    (topic_brief/logline/hook) -- the caller decides how to degrade (an
    unresolved deliverable/platform pair simply has no canonical entry,
    and hypogeum.publishing.cross_platform_readiness is the real gate
    that fails it closed); this module itself never invents one.
    """


def _load_json_if_exists(path: Path) -> dict:
    if not path.exists():
        return {}
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return {}


_LLM_JSON_RETRY_ATTEMPTS = 3


def _default_llm_call(
    system_prompt: str, input_package: dict, *, config: Config,
    episode_id: str, channel_id: Optional[str],
) -> dict:
    from hypogeum.openrouter import call_claude  # noqa: PLC0415

    messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": json.dumps(input_package, ensure_ascii=False)},
    ]
    last_error: Optional[json.JSONDecodeError] = None
    for attempt in range(_LLM_JSON_RETRY_ATTEMPTS):
        call_messages = list(messages)
        if attempt > 0:
            # A prior attempt returned text that failed to parse as JSON --
            # most commonly an unescaped literal quote character inside a
            # string value (e.g. the model quoting source material with "
            # instead of an escaped \"). Retrying with an explicit reminder
            # resolves this in practice; this never changes what content is
            # requested, only how strictly it must be JSON-escaped.
            call_messages.append({
                "role": "user",
                "content": (
                    "Your previous response was not valid JSON "
                    f"({last_error}). Return ONLY the JSON object again, "
                    "with every literal double-quote character inside a "
                    "string value properly escaped as \\\"."
                ),
            })
        result = call_claude(
            model_slug=getattr(config, "CANONICAL_METADATA_MODEL_SLUG", "anthropic/claude-sonnet-4.6"),
            messages=call_messages, max_tokens=4096, config=config,
            episode_id=episode_id, agent=_AGENT_NAME, channel_id=channel_id,
        )
        raw = result.content.strip()
        if raw.startswith("```"):
            raw = raw.strip("`")
            if raw.lower().startswith("json"):
                raw = raw[4:]
        try:
            return json.loads(raw)
        except json.JSONDecodeError as exc:
            last_error = exc
    raise last_error


def _resolve_grounding_text(
    episode_id: str, episode_dir: Path, deliverable_id: str, deliverable_class: str,
    final_render_package: dict,
) -> str:
    """
    main_episode: every real narration_beats[].text across script_package's
    own sections, in order. Short: the ALREADY-GENERATED, script-grounded
    caption for this exact short_id (metadata_source.shorts_captions,
    matched by short_id -- never positional) -- reusing the real content
    hypogeum.agents.shorts_metadata.generate_shorts_captions() already
    produced, never re-deriving it from raw beats a second time.
    """
    if deliverable_class == "main_episode":
        script_package = _load_json_if_exists(episode_dir / f"script_package_{episode_id}.json")
        sections = script_package.get("sections") or []
        beats = [
            beat.get("text", "")
            for section in sections
            for beat in (section.get("narration_beats") or [])
            if isinstance(beat, dict)
        ]
        text = " ".join(b for b in beats if b).strip()
        if not text:
            raise CanonicalMetadataGenerationError(
                f"no real narration_beats found in script_package_{episode_id}.json -- nothing to ground generation in"
            )
        return text

    metadata_source = (final_render_package or {}).get("metadata_source") or {}
    for entry in metadata_source.get("shorts_captions") or []:
        if isinstance(entry, dict) and entry.get("short_id") == deliverable_id:
            caption = (entry.get("caption") or "").strip()
            if caption:
                return caption
    raise CanonicalMetadataGenerationError(
        f"no real, already-resolved caption found in metadata_source.shorts_captions for "
        f"deliverable_id={deliverable_id!r} -- nothing to ground generation in "
        f"(hypogeum.agents.shorts_metadata.generate_shorts_captions() must run first)"
    )


def _resolve_sources_and_claim_map(episode_dir: Path, episode_id: str, *, max_sources: int = 8):
    research_package = _load_json_if_exists(episode_dir / f"research_package_{episode_id}.json")
    source_registry = research_package.get("source_registry") or []
    claims = research_package.get("claims") or []
    if not source_registry:
        raise CanonicalMetadataGenerationError(
            f"research_package_{episode_id}.json has no source_registry -- no verified sources to cite"
        )

    def _well_formed(url: str) -> bool:
        parsed = urlparse(url)
        return parsed.scheme in ("http", "https") and bool(parsed.netloc)

    # Prefer higher-authority source types first, then declared order --
    # never invents a ranking beyond what the Research Package itself
    # already records via inferred_type.
    _TYPE_RANK = {"academic": 0, "official": 1, "expert_analysis": 2, "news_archive": 3}
    ranked = sorted(
        [s for s in source_registry if isinstance(s, dict) and s.get("url") and _well_formed(s["url"])],
        key=lambda s: _TYPE_RANK.get(s.get("inferred_type"), 9),
    )
    selected = ranked[:max_sources]
    if not selected:
        raise CanonicalMetadataGenerationError(
            f"research_package_{episode_id}.json's source_registry has no well-formed http(s) URLs"
        )
    sources = [{"title": s.get("inferred_type", "Source").replace("_", " ").title(), "url": s["url"]} for s in selected]

    selected_ids = {s.get("source_id") for s in selected}
    claim_source_map = {
        c["claim_id"]: {"sources": [sid for sid in c.get("sources", []) if sid in selected_ids]}
        for c in claims if isinstance(c, dict) and c.get("claim_id") and any(sid in selected_ids for sid in c.get("sources", []))
    }
    if not claim_source_map:
        # Fall back to any claim referencing ANY real registry source_id
        # (not just the selected top-N) rather than leaving provenance
        # empty -- still never fabricated, still real IDs from the same
        # Research Package.
        all_ids = {s.get("source_id") for s in source_registry if isinstance(s, dict)}
        claim_source_map = {
            c["claim_id"]: {"sources": [sid for sid in c.get("sources", []) if sid in all_ids]}
            for c in claims if isinstance(c, dict) and c.get("claim_id") and any(sid in all_ids for sid in c.get("sources", []))
        }
    if not claim_source_map:
        raise CanonicalMetadataGenerationError(
            f"research_package_{episode_id}.json has no claim whose sources overlap the real source_registry"
        )
    return sources, claim_source_map


def _resolve_chapters(episode_id: str, episode_dir: Path, final_render_package: dict) -> List[dict]:
    """
    Real per-beat cumulative timestamps from narration_package's own
    measured TTS segment durations, matched to script_package's
    chapter_markers (opening_beat_id) -- the SAME computation manually
    verified against the real ep_f3619022 render (see docs/operations/
    audits/ZERNIO_YOUTUBE_FIELD_MAPPING_2026-08-23.md), cross-validated
    against final_render_package.metadata_source.section_titles when
    present (an earlier pipeline step's own independently-computed
    section start times). Empty list (never fabricated) when either
    source artifact is missing or a referenced beat_id cannot be found --
    the caller/readiness gate is what fails main_episode/youtube closed
    on too-few chapters, never this function inventing one.
    """
    script_package = _load_json_if_exists(episode_dir / f"script_package_{episode_id}.json")
    chapter_markers = script_package.get("chapter_markers") or []
    if not chapter_markers:
        return []

    metadata_source = (final_render_package or {}).get("metadata_source") or {}
    section_titles = {
        s["section_id"]: s["start_seconds"]
        for s in (metadata_source.get("section_titles") or [])
        if isinstance(s, dict) and "section_id" in s and "start_seconds" in s
    }
    if section_titles:
        chapters = []
        for marker in chapter_markers:
            sid = marker.get("section_id")
            if sid not in section_titles:
                return []  # a referenced section is missing -- never partially fabricate
            chapters.append({"start_seconds": float(section_titles[sid]), "title": marker.get("title", "")})
        return chapters

    narration_package = _load_json_if_exists(episode_dir / f"narration_package_{episode_id}.json")
    segments = [
        s for s in (narration_package.get("narration_segments") or [])
        if isinstance(s, dict) and s.get("source_type") == "main_episode"
    ]
    if not segments:
        return []
    segments.sort(key=lambda s: int(str(s.get("beat_reference", "b_0")).split("_")[-1]))
    cumulative: Dict[str, float] = {}
    t = 0.0
    for s in segments:
        cumulative[s["beat_reference"]] = t
        t += float(s.get("duration_seconds", 0.0))

    chapters = []
    for marker in chapter_markers:
        beat_id = marker.get("opening_beat_id")
        if beat_id not in cumulative:
            return []
        chapters.append({"start_seconds": cumulative[beat_id], "title": marker.get("title", "")})
    return chapters


def generate_canonical_platform_metadata_for_deliverable(
    episode_id: str,
    episode_dir: Path,
    deliverable_id: str,
    deliverable_class: str,
    target_platforms: List[str],
    final_render_package: dict,
    *,
    config: Config,
    channel_id: Optional[str] = None,
    platform_deliverable_policy: Optional[dict] = None,
    llm_call: Optional[Callable[..., dict]] = None,
) -> List[dict]:
    """
    Generates one CanonicalPlatformMetadata dict (see
    hypogeum.publishing.canonical_metadata) per platform in
    target_platforms, all in ONE model call (cheaper and more internally
    consistent than one call per platform).

    `platform_deliverable_policy`: the channel's own
    ChannelOperationsProfile.platform_deliverable_policy -- category_id/
    ai_disclosure/platform_policy_fields are read from here (per
    (platform, deliverable_class)), never generated by the model. A
    platform whose policy entry has no explicit "categoryId"/
    "ai_disclosure" simply gets None for that field -- readiness (not
    this function) is what decides whether that blocks submission.

    Raises CanonicalMetadataGenerationError (never returns a partial/
    fabricated result) when grounding content, real sources, the model
    call, or the model's own response for any requested platform is
    unavailable or invalid -- matching hypogeum.agents.shorts_metadata's
    own fail-closed discipline exactly.
    """
    log = get_logger(episode_id=episode_id, agent=_AGENT_NAME)
    if not target_platforms:
        raise CanonicalMetadataGenerationError("target_platforms is empty -- nothing to generate")

    from hypogeum.publishing.zernio_platform_contracts import get_platform_contract

    grounding_text = _resolve_grounding_text(episode_id, episode_dir, deliverable_id, deliverable_class, final_render_package)
    sources, claim_source_map = _resolve_sources_and_claim_map(episode_dir, episode_id)
    source_artifact_ids = [f"research_package_{episode_id}.json"]
    input_fingerprint = {}
    for name in source_artifact_ids:
        p = episode_dir / name
        if p.exists():
            input_fingerprint[name] = hashlib.sha256(p.read_bytes()).hexdigest()

    chapters: List[dict] = []
    if deliverable_class == "main_episode" and "youtube" in target_platforms:
        chapters = _resolve_chapters(episode_id, episode_dir, final_render_package)

    platform_rules = {}
    for platform in target_platforms:
        contract = get_platform_contract(platform)
        platform_rules[platform] = {
            "title_supported": bool(contract and contract.title_supported),
            "description_char_limit": contract.caption_max_chars if contract else None,
            "backend_tags_supported": platform in _PLATFORMS_WITH_BACKEND_TAGS,
            "first_comment_supported": platform in _PLATFORMS_WITH_FIRST_COMMENT,
        }

    call = llm_call or _default_llm_call
    try:
        response = call(
            _SYSTEM_PROMPT.format(
                platform_rules=json.dumps(platform_rules, indent=2), youtube_title_limit=100,
            ),
            {
                "deliverable_class": deliverable_class,
                "grounding_text": grounding_text,
                "sources": sources,
                "platforms": target_platforms,
            },
            config=config, episode_id=episode_id, channel_id=channel_id,
        )
    except Exception as exc:
        log.error("canonical_metadata_generation_failed", deliverable_id=deliverable_id, error=str(exc))
        raise CanonicalMetadataGenerationError(f"canonical metadata generation failed: {exc}") from exc

    by_platform = response.get("platforms") if isinstance(response, dict) else None
    if not isinstance(by_platform, dict):
        raise CanonicalMetadataGenerationError("model response did not contain a 'platforms' object")

    missing = [p for p in target_platforms if p not in by_platform]
    if missing:
        raise CanonicalMetadataGenerationError(f"model response missing platform(s): {missing}")

    now_iso = datetime.now(timezone.utc).isoformat()
    entries: List[dict] = []
    for platform in target_platforms:
        raw = by_platform[platform]
        if not isinstance(raw, dict):
            raise CanonicalMetadataGenerationError(f"model response for platform={platform!r} is not an object")

        description = (raw.get("description") or "").strip()
        if not description:
            raise CanonicalMetadataGenerationError(f"model returned an empty description for platform={platform!r}")
        if description.strip() == grounding_text.strip():
            raise CanonicalMetadataGenerationError(
                f"model returned the raw grounding text verbatim as the description for "
                f"platform={platform!r} -- not real publication copy"
            )
        contract = get_platform_contract(platform)
        if contract and contract.caption_max_chars is not None and len(description) > contract.caption_max_chars:
            raise CanonicalMetadataGenerationError(
                f"model returned a {len(description)}-char description for platform={platform!r}, "
                f"exceeding its documented {contract.caption_max_chars}-char limit"
            )

        visible_hashtags = [h for h in (raw.get("visible_hashtags") or []) if isinstance(h, str) and h.startswith("#")]
        if not visible_hashtags:
            raise CanonicalMetadataGenerationError(f"model returned no visible_hashtags for platform={platform!r}")
        missing_tokens = [h for h in visible_hashtags if h.lower() not in description.lower()]
        if missing_tokens:
            raise CanonicalMetadataGenerationError(
                f"model claimed hashtag(s) {missing_tokens} for platform={platform!r} but they do not "
                f"appear as real tokens in its own description"
            )

        title = (raw.get("title") or "").strip() or None
        if contract and contract.title_supported and not title:
            raise CanonicalMetadataGenerationError(f"model returned no title for platform={platform!r}, which requires one")
        if title and platform == "youtube" and len(title) > 100:
            raise CanonicalMetadataGenerationError(f"model returned a {len(title)}-char YouTube title, exceeding the 100-char limit")

        backend_tags = [t for t in (raw.get("backend_tags") or []) if isinstance(t, str)] if platform in _PLATFORMS_WITH_BACKEND_TAGS else []
        overlap = {t.lower().lstrip("#") for t in backend_tags} & {h.lower().lstrip("#") for h in visible_hashtags}
        if overlap:
            raise CanonicalMetadataGenerationError(f"model returned overlapping backend_tags/visible_hashtags for platform={platform!r}: {sorted(overlap)}")

        cta = (raw.get("cta") or "").strip() or None
        first_comment = (raw.get("first_comment") or "").strip() or None
        if platform not in _PLATFORMS_WITH_FIRST_COMMENT:
            first_comment = None

        class_entry = ((platform_deliverable_policy or {}).get(platform) or {}).get(deliverable_class, {})

        entries.append({
            "deliverable_id": deliverable_id, "platform": platform,
            "title": title, "description": description,
            "visible_hashtags": visible_hashtags, "backend_tags": backend_tags,
            "sources": sources, "claim_source_map": claim_source_map,
            "cta": cta, "language": "en", "metadata_version": "v1",
            "source_artifact_ids": source_artifact_ids, "input_fingerprint": input_fingerprint,
            "generated_at": now_iso, "approved_at": now_iso,
            "first_comment": first_comment,
            "category_id": class_entry.get("categoryId"),
            "thumbnail_ref": None,  # caller fills in from its own already-resolved thumbnail path
            "ai_disclosure": class_entry.get("ai_disclosure"),
            "chapters": chapters if platform == "youtube" and deliverable_class == "main_episode" else [],
        })

    # Distinct-across-platforms check, matching shorts_metadata.py's own
    # "distinct across Shorts" discipline -- silent reuse of one generic
    # caption across all platforms is exactly the defect item 3 prohibits.
    distinct_descriptions = {e["description"].strip().lower() for e in entries}
    if len(distinct_descriptions) != len(entries) and len(entries) > 1:
        raise CanonicalMetadataGenerationError(
            "model returned two or more identical descriptions across distinct platforms -- "
            "each platform requires its own genuine variant"
        )

    return entries
