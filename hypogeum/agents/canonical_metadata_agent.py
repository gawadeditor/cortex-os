"""
hypogeum/agents/canonical_metadata_agent.py — Generates the real,
per-(deliverable_id, platform) canonical publication metadata package
(hypogeum.publishing.canonical_metadata.CanonicalPlatformMetadata shape)
that hypogeum.publishing.cross_platform_readiness now REQUIRES before any
Zernio submission for every enabled deliverable/platform pair.

Fixed 2026-08-23 (permanent workflow, not a one-off ep_f3619022 repair --
see docs/operations/audits/ZERNIO_CANONICAL_METADATA_CONTRACT_2026-08-23.md):
prior to this module, a canonical_platform_metadata entry could only ever
be created by hand (a human-written repair artifact) -- there was no
automatic path back to a resolved value for a freshly-produced episode,
which is exactly the class of defect that let ep_f3619022 reach Zernio
with every platform-specific field blank. This module closes that gap:
called automatically (see build_publish_package_from_episode_dir()) for
any (deliverable_id, platform) pair missing a canonical entry.

Grounding against fabrication, same discipline as
hypogeum.agents.shorts_metadata: the model is given ONLY that
deliverable's own real script content (narration_beats for a main
episode's sections, or the SAME already-generated, script-grounded
caption hypogeum.agents.shorts_metadata.generate_shorts_captions()
produced for a Short) and that episode's own real, verified Research
Package sources -- it may never introduce a fact, name, date, claim, or
source URL that does not already exist in those real artifacts.

Deterministic fields (chapters, sources, claim_source_map,
source_artifact_ids, input_fingerprint, generated_at/approved_at) are
computed directly from real on-disk artifacts, NEVER generated by the
model -- only title/description/CTA/visible_hashtags/backend_tags/
first_comment are model-generated, and even those are validated
(non-empty, non-placeholder, hashtags as real tokens, distinct per
platform) before being accepted. category_id/ai_disclosure/
platform_policy_fields are channel-policy values (never generated
per-episode) -- supplied by the caller from the channel's own
platform_deliverable_policy, never invented here.

Public API:
    CanonicalMetadataGenerationError
    generate_canonical_platform_metadata_for_deliverable(
        episode_id, episode_dir, deliverable_id, deliverable_class,
        target_platforms, final_render_package, *, config, channel_id=None,
        platform_deliverable_policy=None, llm_call=None) -> List[dict]
"""

