class CanonicalMetadataGenerationError(RuntimeError):
    """
    Raised when a real, grounded canonical metadata package cannot be
    produced for every requested platform. Never caught here to silently
    fall back to a placeholder, generic content, or a research artifact
    (topic_brief/logline/hook) -- the caller decides how to degrade (an
    unresolved deliverable/platform pair simply has no canonical entry,
    and hypogeum.publishing.cross_platform_readiness is the real gate
    that fails it closed); this module itself never invents one.
    """


def _load_json_if_exists(path: Path) -> dict:
    if not path.exists():
        return {}
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return {}


def _default_llm_call(
    system_prompt: str, input_package: dict, *, config: Config,
    episode_id: str, channel_id: Optional[str],
) -> dict:
    """
    Single-shot: one real model call, parsed once. Bounded retry (JSON
    parse failures AND validation failures alike, with the exact error
    fed back into the next attempt's system_prompt) lives in the CALLER,
    generate_canonical_platform_metadata_for_deliverable() -- consolidated
    there 2026-08-23 so "max 3 attempts" is one real bound across both
    failure classes, not two independently-bounded retry loops stacked on
    top of each other (which would allow up to 9 raw calls for a single
    deliverable). See that function's _MAX_GENERATION_ATTEMPTS.
    """
    from hypogeum.openrouter import call_claude  # noqa: PLC0415

    messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": json.dumps(input_package, ensure_ascii=False)},
    ]
    result = call_claude(
        model_slug=getattr(config, "CANONICAL_METADATA_MODEL_SLUG", "anthropic/claude-sonnet-4.6"),
        messages=messages, max_tokens=4096, config=config,
        episode_id=episode_id, agent=_AGENT_NAME, channel_id=channel_id,
    )
    raw = result.content.strip()
    if raw.startswith("```"):
        raw = raw.strip("`")
        if raw.lower().startswith("json"):
            raw = raw[4:]
    return json.loads(raw)


def _resolve_grounding_text(
    episode_id: str, episode_dir: Path, deliverable_id: str, deliverable_class: str,
    final_render_package: dict,
) -> str:
    """
    main_episode: every real narration_beats[].text across script_package's
    own sections, in order. Short: the ALREADY-GENERATED, script-grounded
    caption for this exact short_id (metadata_source.shorts_captions,
    matched by short_id -- never positional) -- reusing the real content
    hypogeum.agents.shorts_metadata.generate_shorts_captions() already
    produced, never re-deriving it from raw beats a second time.
    """
    if deliverable_class == "main_episode":
        script_package = _load_json_if_exists(episode_dir / f"script_package_{episode_id}.json")
        sections = script_package.get("sections") or []
        beats = [
            beat.get("text", "")
            for section in sections
            for beat in (section.get("narration_beats") or [])
            if isinstance(beat, dict)
        ]
        text = " ".join(b for b in beats if b).strip()
        if not text:
            raise CanonicalMetadataGenerationError(
                f"no real narration_beats found in script_package_{episode_id}.json -- nothing to ground generation in"
            )
        return text

    metadata_source = (final_render_package or {}).get("metadata_source") or {}
    for entry in metadata_source.get("shorts_captions") or []:
        if isinstance(entry, dict) and entry.get("short_id") == deliverable_id:
            caption = (entry.get("caption") or "").strip()
            if caption:
                return caption
    raise CanonicalMetadataGenerationError(
        f"no real, already-resolved caption found in metadata_source.shorts_captions for "
        f"deliverable_id={deliverable_id!r} -- nothing to ground generation in "
        f"(hypogeum.agents.shorts_metadata.generate_shorts_captions() must run first)"
    )


def _resolve_sources_and_claim_map(episode_dir: Path, episode_id: str, *, max_sources: int = 8):
    research_package = _load_json_if_exists(episode_dir / f"research_package_{episode_id}.json")
    source_registry = research_package.get("source_registry") or []
    claims = research_package.get("claims") or []
    if not source_registry:
        raise CanonicalMetadataGenerationError(
            f"research_package_{episode_id}.json has no source_registry -- no verified sources to cite"
        )

    def _well_formed(url: str) -> bool:
        parsed = urlparse(url)
        return parsed.scheme in ("http", "https") and bool(parsed.netloc)

    # Prefer higher-authority source types first, then declared order --
    # never invents a ranking beyond what the Research Package itself
    # already records via inferred_type.
    _TYPE_RANK = {"academic": 0, "official": 1, "expert_analysis": 2, "news_archive": 3}
    ranked = sorted(
        [s for s in source_registry if isinstance(s, dict) and s.get("url") and _well_formed(s["url"])],
        key=lambda s: _TYPE_RANK.get(s.get("inferred_type"), 9),
    )
    selected = ranked[:max_sources]
    if not selected:
        raise CanonicalMetadataGenerationError(
            f"research_package_{episode_id}.json's source_registry has no well-formed http(s) URLs"
        )
    sources = [{"title": s.get("inferred_type", "Source").replace("_", " ").title(), "url": s["url"]} for s in selected]

    selected_ids = {s.get("source_id") for s in selected}
    claim_source_map = {
        c["claim_id"]: {"sources": [sid for sid in c.get("sources", []) if sid in selected_ids]}
        for c in claims if isinstance(c, dict) and c.get("claim_id") and any(sid in selected_ids for sid in c.get("sources", []))
    }
    if not claim_source_map:
        # Fall back to any claim referencing ANY real registry source_id
        # (not just the selected top-N) rather than leaving provenance
        # empty -- still never fabricated, still real IDs from the same
        # Research Package.
        all_ids = {s.get("source_id") for s in source_registry if isinstance(s, dict)}
        claim_source_map = {
            c["claim_id"]: {"sources": [sid for sid in c.get("sources", []) if sid in all_ids]}
            for c in claims if isinstance(c, dict) and c.get("claim_id") and any(sid in all_ids for sid in c.get("sources", []))
        }
    if not claim_source_map:
        raise CanonicalMetadataGenerationError(
            f"research_package_{episode_id}.json has no claim whose sources overlap the real source_registry"
        )
    return sources, claim_source_map


def _resolve_chapters(episode_id: str, episode_dir: Path, final_render_package: dict) -> List[dict]:
    """
    Real per-beat cumulative timestamps from narration_package's own
    measured TTS segment durations, matched to script_package's
    chapter_markers (opening_beat_id) -- the SAME computation manually
    verified against the real ep_f3619022 render (see docs/operations/
    audits/ZERNIO_YOUTUBE_FIELD_MAPPING_2026-08-23.md), cross-validated
    against final_render_package.metadata_source.section_titles when
    present (an earlier pipeline step's own independently-computed
    section start times). Empty list (never fabricated) when either
    source artifact is missing or a referenced beat_id cannot be found --
    the caller/readiness gate is what fails main_episode/youtube closed
    on too-few chapters, never this function inventing one.
    """
    script_package = _load_json_if_exists(episode_dir / f"script_package_{episode_id}.json")
    chapter_markers = script_package.get("chapter_markers") or []
    if not chapter_markers:
        return []

    metadata_source = (final_render_package or {}).get("metadata_source") or {}
    section_titles = {
        s["section_id"]: s["start_seconds"]
        for s in (metadata_source.get("section_titles") or [])
        if isinstance(s, dict) and "section_id" in s and "start_seconds" in s
    }
    if section_titles:
        chapters = []
        for marker in chapter_markers:
            sid = marker.get("section_id")
            if sid not in section_titles:
                return []  # a referenced section is missing -- never partially fabricate
            chapters.append({"start_seconds": float(section_titles[sid]), "title": marker.get("title", "")})
        return chapters

    narration_package = _load_json_if_exists(episode_dir / f"narration_package_{episode_id}.json")
    segments = [
        s for s in (narration_package.get("narration_segments") or [])
        if isinstance(s, dict) and s.get("source_type") == "main_episode"
    ]
    if not segments:
        return []
    segments.sort(key=lambda s: int(str(s.get("beat_reference", "b_0")).split("_")[-1]))
    cumulative: Dict[str, float] = {}
    t = 0.0
    for s in segments:
        cumulative[s["beat_reference"]] = t
        t += float(s.get("duration_seconds", 0.0))

    chapters = []
    for marker in chapter_markers:
        beat_id = marker.get("opening_beat_id")
        if beat_id not in cumulative:
            return []
        chapters.append({"start_seconds": cumulative[beat_id], "title": marker.get("title", "")})
    return chapters


_MAX_GENERATION_ATTEMPTS = 3


def _validate_and_build_entries(
    response, *, target_platforms: List[str], grounding_text: str, sources, claim_source_map,
    source_artifact_ids: List[str], input_fingerprint: dict, chapters: List[dict],
    deliverable_id: str, deliverable_class: str,
    platform_deliverable_policy: Optional[dict], now_iso: str,
) -> "tuple[List[dict], List[str]]":
    """
    Validates one raw model response against every requested platform's
    rules, collecting EVERY problem found (never stopping at the first)
    so a retry can be told everything wrong in one pass. Returns
    (entries, errors) -- entries is [] whenever errors is non-empty; a
    partially-valid response is never partially accepted.
    """
    from hypogeum.publishing.canonical_metadata import (
        CanonicalPlatformMetadata,
        extract_hashtag_tokens,
        materialize_youtube_main_episode_description,
    )
    from hypogeum.publishing.zernio_platform_contracts import get_platform_contract

    errors: List[str] = []
    by_platform = response.get("platforms") if isinstance(response, dict) else None
    if not isinstance(by_platform, dict):
        return [], ["model response did not contain a 'platforms' object"]

    missing = [p for p in target_platforms if p not in by_platform]
    if missing:
        errors.append(f"model response is missing platform(s) entirely: {missing}")

    now_iso = now_iso
    entries: List[dict] = []
    for platform in target_platforms:
        if platform not in by_platform:
            continue
        raw = by_platform[platform]
        if not isinstance(raw, dict):
            errors.append(f"platform={platform!r}: model response entry is not an object")
            continue

        platform_errors: List[str] = []
        contract = get_platform_contract(platform)

        description = (raw.get("description") or "").strip()
        if not description:
            platform_errors.append(f"platform={platform!r}: description is empty")
        elif description.strip() == grounding_text.strip():
            platform_errors.append(
                f"platform={platform!r}: description is the raw grounding text verbatim -- write "
                f"real publication copy, never echo the source text"
            )
        elif contract and contract.caption_max_chars is not None:
            # A YouTube main_episode's ACTUAL published content is the
            # materialized description (base + deterministic chapters +
            # sources), never the raw base text alone -- validate THAT
            # length, using the SAME shared function readiness and the
            # real Zernio request use, so a base description that looks
            # fine here can never still blow the limit once chapters/
            # sources are appended downstream.
            if deliverable_class == "main_episode" and platform == "youtube":
                materialized = materialize_youtube_main_episode_description(CanonicalPlatformMetadata(
                    deliverable_id=deliverable_id, platform=platform, description=description,
                    metadata_version="v1", source_artifact_ids=source_artifact_ids,
                    input_fingerprint=input_fingerprint, generated_at=now_iso,
                    chapters=chapters, sources=sources,
                ))
                check_len, check_label = len(materialized), "materialized description (base + chapters + sources)"
            else:
                check_len, check_label = len(description), "description"
            if check_len > contract.caption_max_chars:
                overflow = check_len - contract.caption_max_chars
                platform_errors.append(
                    f"platform={platform!r}: {check_label} is {check_len} chars, exceeding the documented "
                    f"{contract.caption_max_chars}-char limit by {overflow} -- shorten the BASE description "
                    f"by at least {overflow} characters (chapters and sources are appended automatically and "
                    f"cannot be shortened); never truncate mid-sentence"
                )

        visible_hashtags = [h for h in (raw.get("visible_hashtags") or []) if isinstance(h, str) and h.startswith("#")]
        if not visible_hashtags:
            platform_errors.append(f"platform={platform!r}: visible_hashtags is empty")
        else:
            # Real complete-hashtag-token match, never substring -- '#Test'
            # must not pass against a description containing only
            # '#TestTagExtra'. The ONE shared validator with the
            # readiness-side check in hypogeum.publishing.canonical_metadata
            # (2026-08-23; this used to be a broken 'h.lower() in
            # description.lower()' substring check).
            desc_tokens = extract_hashtag_tokens(description)
            missing_tokens = [h for h in visible_hashtags if h.lower() not in desc_tokens]
            if missing_tokens:
                platform_errors.append(
                    f"platform={platform!r}: hashtag(s) {missing_tokens} were listed in visible_hashtags "
                    f"but do not appear as complete hashtag tokens inside the description text itself "
                    f"(a substring of a longer hashtag does not count)"
                )

        title = (raw.get("title") or "").strip() or None
        if contract and contract.title_supported and not title:
            platform_errors.append(f"platform={platform!r}: title is required but missing")
        if title and platform == "youtube" and len(title) > 100:
            platform_errors.append(
                f"platform={platform!r}: title is {len(title)} chars, exceeding YouTube's 100-char limit -- "
                f"shorten it, never truncate mid-word"
            )

        backend_tags = [t for t in (raw.get("backend_tags") or []) if isinstance(t, str)] if platform in _PLATFORMS_WITH_BACKEND_TAGS else []
        overlap = {t.lower().lstrip("#") for t in backend_tags} & {h.lower().lstrip("#") for h in visible_hashtags}
        if overlap:
            platform_errors.append(
                f"platform={platform!r}: backend_tags and visible_hashtags overlap (must stay separate "
                f"concepts): {sorted(overlap)}"
            )

        if platform_errors:
            errors.extend(platform_errors)
            continue

        cta = (raw.get("cta") or "").strip() or None
        first_comment = (raw.get("first_comment") or "").strip() or None
        if platform not in _PLATFORMS_WITH_FIRST_COMMENT:
            first_comment = None

        class_entry = ((platform_deliverable_policy or {}).get(platform) or {}).get(deliverable_class, {})

        entries.append({
            "deliverable_id": deliverable_id, "platform": platform,
            "title": title, "description": description,
            "visible_hashtags": visible_hashtags, "backend_tags": backend_tags,
            "sources": sources, "claim_source_map": claim_source_map,
            "cta": cta, "language": "en", "metadata_version": "v1",
            "source_artifact_ids": source_artifact_ids, "input_fingerprint": input_fingerprint,
            "generated_at": now_iso, "approved_at": now_iso,
            "first_comment": first_comment,
            "category_id": class_entry.get("categoryId"),
            "thumbnail_ref": None,  # caller fills in from its own already-resolved thumbnail path
            "ai_disclosure": class_entry.get("ai_disclosure"),
            "chapters": chapters if platform == "youtube" and deliverable_class == "main_episode" else [],
        })

    if errors:
        return [], errors

    # Distinct-across-platforms check, matching shorts_metadata.py's own
    # "distinct across Shorts" discipline -- silent reuse of one generic
    # caption across all platforms is exactly the defect item 3 prohibits.
    distinct_descriptions = {e["description"].strip().lower() for e in entries}
    if len(distinct_descriptions) != len(entries) and len(entries) > 1:
        return [], [
            "two or more platforms received identical descriptions -- each platform requires "
            "its own genuine variant, never a copy-pasted one"
        ]

    return entries, []


def generate_canonical_platform_metadata_for_deliverable(
    episode_id: str,
    episode_dir: Path,
    deliverable_id: str,
    deliverable_class: str,
    target_platforms: List[str],
    final_render_package: dict,
    *,
    config: Config,
    channel_id: Optional[str] = None,
    platform_deliverable_policy: Optional[dict] = None,
    llm_call: Optional[Callable[..., dict]] = None,
) -> List[dict]:
    """
    Generates one CanonicalPlatformMetadata dict (see
    hypogeum.publishing.canonical_metadata) per platform in
    target_platforms, all in ONE model call per attempt (cheaper and more
    internally consistent than one call per platform).

    `platform_deliverable_policy`: the channel's own
    ChannelOperationsProfile.platform_deliverable_policy -- category_id/
    ai_disclosure/platform_policy_fields are read from here (per
    (platform, deliverable_class)), never generated by the model.

    Policy-completeness pre-check (2026-08-23, atomic per deliverable,
    zero wasted model calls): before ANY model call, every requested
    platform's declared PlatformContract.required_policy_fields (e.g.
    youtube's "categoryId", mandatory once youtube is enabled -- see
    hypogeum.publishing.zernio_platform_contracts) is checked against
    platform_deliverable_policy. If ANY requested platform is missing a
    required field, the ENTIRE call fails closed -- no platform is
    generated for, not even a policy-complete sibling. A publishing
    release for one deliverable submits every enabled target platform
    together or none of them; silently dropping one incomplete platform
    while proceeding for the rest would violate that invariant (a
    partial release is not "safe", it's a different, unauthorized
    release). The model is never called in this case -- "before metadata
    generation, zero external calls", not merely "before the Zernio
    call".

    Bounded automatic regeneration (2026-08-23, replaces the earlier
    manual-rerun requirement): up to _MAX_GENERATION_ATTEMPTS (3) real
    model calls. A JSON parse failure OR any field-validation failure
    (description/title length, missing required fields, invalid hashtag
    formatting, backend/hashtag overlap, verbatim-grounding reuse,
    non-distinct-across-platforms) is fed back into the NEXT attempt's
    prompt as an explicit, itemized list of exactly what to fix -- never
    silently truncates or patches an invalid value itself. Only a fully
    validated response is ever persisted; after the final failed attempt,
    raises CanonicalMetadataGenerationError with the precise, complete
    list of what still failed. Deterministic fields (sources,
    claim_source_map, chapters, source_artifact_ids, input_fingerprint)
    are computed once, outside the retry loop -- they never come from the
    model, so there is nothing about them for a retry to "fix".
    """
    log = get_logger(episode_id=episode_id, agent=_AGENT_NAME)
    if not target_platforms:
        raise CanonicalMetadataGenerationError("target_platforms is empty -- nothing to generate")

    from hypogeum.publishing.canonical_metadata import is_required_policy_field_present
    from hypogeum.publishing.zernio_platform_contracts import get_platform_contract

    # Policy-completeness pre-check -- BEFORE any grounding resolution or
    # model call. Atomic per deliverable: if ANY requested platform's
    # Channel Package lacks a field its own contract declares mandatory,
    # the WHOLE call fails closed -- never a partial generation that
    # drops the incomplete platform and proceeds for the rest (that would
    # let one enabled platform release ahead of a sibling that shares the
    # same deliverable, violating "every enabled target platform ready
    # before any platform submits"). Presence uses the ONE shared
    # validator (is_required_policy_field_present) -- a required boolean
    # field legitimately set to False is present, not missing.
    policy_incomplete: Dict[str, List[str]] = {}
    for platform in target_platforms:
        contract = get_platform_contract(platform)
        required_fields = getattr(contract, "required_policy_fields", ()) or ()
        class_entry = ((platform_deliverable_policy or {}).get(platform) or {}).get(deliverable_class, {})
        missing_fields = [f for f in required_fields if not is_required_policy_field_present(class_entry, f)]
        if missing_fields:
            policy_incomplete[platform] = missing_fields

    if policy_incomplete:
        log.error(
            "canonical_metadata_policy_incomplete", deliverable_id=deliverable_id,
            deliverable_class=deliverable_class, policy_incomplete=policy_incomplete,
        )
        raise CanonicalMetadataGenerationError(
            f"channel policy is missing required field(s) for deliverable_id={deliverable_id!r} -- "
            f"refusing to generate for ANY of its target platforms (atomic per-deliverable "
            f"readiness), zero model calls made: {policy_incomplete}"
        )

    grounding_text = _resolve_grounding_text(episode_id, episode_dir, deliverable_id, deliverable_class, final_render_package)
    sources, claim_source_map = _resolve_sources_and_claim_map(episode_dir, episode_id)
    source_artifact_ids = [f"research_package_{episode_id}.json"]
    input_fingerprint = {}
    for name in source_artifact_ids:
        p = episode_dir / name
        if p.exists():
            input_fingerprint[name] = hashlib.sha256(p.read_bytes()).hexdigest()

    chapters: List[dict] = []
    if deliverable_class == "main_episode" and "youtube" in target_platforms:
        chapters = _resolve_chapters(episode_id, episode_dir, final_render_package)

    platform_rules = {}
    for platform in target_platforms:
        contract = get_platform_contract(platform)
        platform_rules[platform] = {
            "title_supported": bool(contract and contract.title_supported),
            "description_char_limit": contract.caption_max_chars if contract else None,
            "backend_tags_supported": platform in _PLATFORMS_WITH_BACKEND_TAGS,
            "first_comment_supported": platform in _PLATFORMS_WITH_FIRST_COMMENT,
        }

    base_system_prompt = _SYSTEM_PROMPT.format(
        platform_rules=json.dumps(platform_rules, indent=2), youtube_title_limit=100,
    )

    # Channel discovery context — genre/format/audience the tags must lean on.
    # A new channel has no name recognition, so discovery comes almost entirely
    # from generic category/format/audience search, not from episode specifics.
    channel_context = None
    try:
        from hypogeum.channel_creative_brief import channel_brief_for  # noqa: PLC0415
        _brief = channel_brief_for(channel_id) if channel_id else {}
        if _brief:
            channel_context = {
                "channel_name": _brief.get("channel_name") or "",
                "genre": _brief.get("genre") or "",
                "format": _brief.get("format") or "",
                "audience": _brief.get("audience") or "",
                "language": _brief.get("language") or "en",
                "content_pillars": _brief.get("content_pillars") or [],
                "brand_is_unknown": True,
            }
    except Exception as exc:  # noqa: BLE001
        log.warn("canonical_metadata_channel_context_unavailable",
                 deliverable_id=deliverable_id, error=str(exc))

    # Researched discovery intelligence (competitor hashtags, high-volume
    # search terms, trending queries) — cached per channel, refreshed off the
    # episode path. Absent until the first research run; strengthens the
    # generic-search strategy above when present.
    try:
        from hypogeum.channel_keyword_research import keyword_context_for_metadata  # noqa: PLC0415
        _research = keyword_context_for_metadata(channel_id) if channel_id else None
        if _research:
            if channel_context is None:
                channel_context = {"brand_is_unknown": True}
            channel_context["competitor_hashtags"] = _research["competitor_hashtags"]
            channel_context["high_volume_search_terms"] = _research["high_volume_search_terms"]
            channel_context["trending_terms"] = _research["trending_terms"]
            channel_context["audience_questions"] = _research["audience_questions"]
    except Exception as exc:  # noqa: BLE001
        log.warn("canonical_metadata_keyword_research_unavailable",
                 deliverable_id=deliverable_id, error=str(exc))

    input_package = {
        "deliverable_class": deliverable_class,
        "grounding_text": grounding_text,
        "sources": sources,
        "platforms": target_platforms,
    }
    if channel_context:
        input_package["channel_context"] = channel_context
    call = llm_call or _default_llm_call
    now_iso = datetime.now(timezone.utc).isoformat()

    last_errors: List[str] = []
    for attempt in range(1, _MAX_GENERATION_ATTEMPTS + 1):
        system_prompt = base_system_prompt
        if last_errors:
            system_prompt += (
                "\n\nYour previous attempt failed validation. Fix EXACTLY these problems in this "
                "response -- do not repeat any of them:\n" + "\n".join(f"- {e}" for e in last_errors)
            )
        try:
            response = call(
                system_prompt, input_package,
                config=config, episode_id=episode_id, channel_id=channel_id,
            )
        except Exception as exc:
            last_errors = [f"response could not be parsed as valid JSON: {exc}"]
            log.warn(
                "canonical_metadata_generation_attempt_failed", deliverable_id=deliverable_id,
                attempt=attempt, max_attempts=_MAX_GENERATION_ATTEMPTS, error=last_errors[0],
            )
            continue

        entries, errors = _validate_and_build_entries(
            response, target_platforms=target_platforms, grounding_text=grounding_text,
            sources=sources, claim_source_map=claim_source_map,
            source_artifact_ids=source_artifact_ids, input_fingerprint=input_fingerprint,
            chapters=chapters, deliverable_id=deliverable_id, deliverable_class=deliverable_class,
            platform_deliverable_policy=platform_deliverable_policy, now_iso=now_iso,
        )
        if not errors:
            if attempt > 1:
                log.info(
                    "canonical_metadata_generation_recovered", deliverable_id=deliverable_id,
                    attempt=attempt, max_attempts=_MAX_GENERATION_ATTEMPTS,
                )
            return entries

        last_errors = errors
        log.warn(
            "canonical_metadata_generation_attempt_failed", deliverable_id=deliverable_id,
            attempt=attempt, max_attempts=_MAX_GENERATION_ATTEMPTS, errors=errors,
        )

    log.error(
        "canonical_metadata_generation_failed", deliverable_id=deliverable_id,
        attempts=_MAX_GENERATION_ATTEMPTS, errors=last_errors,
    )
    raise CanonicalMetadataGenerationError(
        f"canonical metadata generation failed after {_MAX_GENERATION_ATTEMPTS} attempts for "
        f"deliverable_id={deliverable_id!r}: {last_errors}"
    )
