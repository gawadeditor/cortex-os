"""
hypogeum/channel_video_comparison.py — per-channel video-model head-to-head.

A channel's scenes are all generated by one video model (its adopted
ModelProfile). This module holds a saved side-by-side comparison of that
model against one alternative, run on the SAME real prompt from one of the
channel's own episodes, so the operator can judge quality against cost
before switching.

The comparison payload lives on disk at
  .hypogeum-assets/model_comparisons/<channel_id>/comparison.json
plus one <model>.mp4 clip per model in the same directory. `get_comparison`
reads it and overlays the current effective (actually-billed) price from
hypogeum.model_effective_pricing so the cost column never goes stale.

(Distinct from hypogeum.model_comparison, which is the LLM prompt-output
benchmark engine.)

Public API:
    comparison_dir(channel_id) -> Path
    has_comparison(channel_id) -> bool
    get_comparison(channel_id, *, db_path=None) -> dict | None
    clip_path(channel_id, model) -> Path | None
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Optional

_ROOT = Path(__file__).resolve().parent.parent / ".hypogeum-assets" / "model_comparisons"

_SCENES_PER_EPISODE = 15
_UPSCALE_PER_CLIP = 0.05


def comparison_dir(channel_id: str) -> Path:
    return _ROOT / channel_id


def has_comparison(channel_id: str) -> bool:
    return (comparison_dir(channel_id) / "comparison.json").is_file()


def clip_path(channel_id: str, model: str) -> Optional[Path]:
    """The saved clip for `model` in this channel's comparison, or None.
    `model` is matched against the recorded clip_file stems only — no
    arbitrary path is accepted."""
    d = comparison_dir(channel_id)
    rec_path = d / "comparison.json"
    if not rec_path.is_file():
        return None
    try:
        rec = json.loads(rec_path.read_text())
    except (OSError, ValueError):
        return None
    allowed = {rec.get(role, {}).get("clip_file") for role in ("current", "alternative")}
    allowed.discard(None)
    for name in allowed:
        if name and Path(name).stem == model:
            p = d / name
            return p if p.is_file() else None
    return None


def get_comparison(channel_id: str, *, db_path: Optional[Path] = None) -> Optional[dict]:
    """The saved comparison for `channel_id`, with `price_per_call` / `cost_*`
    fields refreshed from live billing history. None if there is no saved
    comparison. Never raises."""
    rec_path = comparison_dir(channel_id) / "comparison.json"
    if not rec_path.is_file():
        return None
    try:
        rec = json.loads(rec_path.read_text())
    except (OSError, ValueError):
        return None

    try:
        from hypogeum.model_effective_pricing import effective_prices
        spend = effective_prices(db_path=db_path)
    except Exception:  # noqa: BLE001
        spend = {}

    for role in ("current", "alternative"):
        m = rec.get(role)
        if not isinstance(m, dict):
            continue
        s = spend.get(m.get("model"))
        if s and s.effective_price:
            m["price_per_call"] = round(s.effective_price, 4)
            m["billed_calls"] = s.n_calls
        gen = float(m.get("price_per_call") or 0)
        dur = float(m.get("duration_s") or 0) or None
        m["cost_gen"] = round(gen, 3)
        m["cost_upscale"] = _UPSCALE_PER_CLIP
        m["cost_per_shot_total"] = round(gen + _UPSCALE_PER_CLIP, 3)
        m["cost_per_second"] = round(gen / dur, 3) if dur else None
        m["cost_per_episode"] = round((gen + _UPSCALE_PER_CLIP) * _SCENES_PER_EPISODE, 2)
        m["cost_per_week"] = round((gen + _UPSCALE_PER_CLIP) * _SCENES_PER_EPISODE * 7, 2)
        m["clip_url"] = f"/channel/{channel_id}/video-compare/clip/{Path(m.get('clip_file', '')).stem}"

    cur, alt = rec.get("current") or {}, rec.get("alternative") or {}
    if cur and alt:
        rec["delta"] = {
            "per_shot": round(alt.get("cost_per_shot_total", 0) - cur.get("cost_per_shot_total", 0), 3),
            "per_episode": round(alt.get("cost_per_episode", 0) - cur.get("cost_per_episode", 0), 2),
            "per_week": round(alt.get("cost_per_week", 0) - cur.get("cost_per_week", 0), 2),
        }
    rec["channel_id"] = channel_id
    return rec
