#!/usr/bin/env python3
"""
tools/regenerate_stale_covers.py — replace a pre-fix vertical cover with a
freshly-generated one, for still-SCHEDULED (never-published) short-native
posts only.

`scripts/backfill_vertical_covers.py` skips any post that already has a
`mediaItems[].thumbnail` — correct for its original job (fill covers that
never existed), but it means a cover generated by the very first version
of the feature (commit d21df8c, 2026-09-08 09:21 UTC) never gets replaced,
even though the safe-zone/typography fix (`1f9ca0d`+`b98d544`, both
2026-09-08 ~11:47-11:52 UTC) landed less than 2.5 hours later. Found
2026-09-11 when `ep_5229bce7` published with its text overlapping the
platform-UI zone (baked-in text at ~72-98% of frame height, well past the
documented "bottom 30% must be background-only" rule) — the cover was one
of a ~50-minute batch generated at 10:12-11:03 UTC, entirely before the
fix. A sweep of every still-scheduled post found **21 of them** carry a
cover from that same pre-fix window.

This tool: for every future-scheduled short-native post, extracts the
upload timestamp embedded in the current `mediaItems[].thumbnail` URL
(`.../media/<epoch_ms>_...`), and if it falls in the pre-fix window
(2026-09-08 09:21:53 - 11:47:41 UTC), regenerates the cover with the
CURRENT prompt/pipeline and PUTs it in place of the stale one. A post
whose cover timestamp can't be parsed, or that predates the window
(shouldn't happen — the feature didn't exist yet), or postdates the fix,
is left alone. **Never touches an already-published post** — same
safety rule as backfill_vertical_covers.py; a live post's frozen cover
is a separate, already-settled question (see
tools/cover_published_shorts.py — Zernio rejects that PUT outright).

Cost ≈ $0.10/episode (one gpt-image-2 gen + one Sonnet call) plus a free
Zernio PUT.

    python3 tools/regenerate_stale_covers.py               # dry run (default)
    python3 tools/regenerate_stale_covers.py --execute      # do it
    python3 tools/regenerate_stale_covers.py --execute --episode ep_566e3f91
"""
from __future__ import annotations

import argparse
import re
import sys
import tempfile
import datetime
from pathlib import Path

_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_ROOT))

from hypogeum.config import Config
from hypogeum.db import get_connection
from hypogeum.logger import get_logger
from scripts.backfill_vertical_covers import (
    _short_native_channels, _resolve_posts, _episode_meta,
    _synth_concept_brief, _stage_cover,
)

log = get_logger(agent="regenerate_stale_covers")

_FEATURE_START = datetime.datetime(2026, 9, 8, 9, 21, 53, tzinfo=datetime.timezone.utc)
_FIX_LANDED = datetime.datetime(2026, 9, 8, 11, 47, 41, tzinfo=datetime.timezone.utc)
_TS_RE = re.compile(r"/media/(\d{10,})_")


def _cover_generated_at(thumbnail_url: str):
    m = _TS_RE.search(thumbnail_url or "")
    if not m:
        return None
    return datetime.datetime.fromtimestamp(int(m.group(1)) / 1000, tz=datetime.timezone.utc)


def run(execute: bool, only_episode: str | None) -> int:
    config = Config()
    if execute and getattr(config, "MUAPI_DRY_RUN", False):
        print("MUAPI_DRY_RUN is true — refusing to run (would not produce a real image).")
        return 2

    conn = get_connection(None)
    try:
        channels = _short_native_channels(conn)
        rows = conn.execute(
            "SELECT DISTINCT episode_id, channel_id, MIN(slot_utc) AS next_slot "
            "FROM channel_publish_slots WHERE slot_utc > datetime('now') "
            "GROUP BY episode_id, channel_id ORDER BY next_slot"
        ).fetchall()
    finally:
        conn.close()
    targets = [
        (r["episode_id"], r["channel_id"], r["next_slot"]) for r in rows
        if r["channel_id"] in channels and (not only_episode or r["episode_id"] == only_episode)
    ]

    from hypogeum.publishing.provider import MediaReference
    from hypogeum.publishing.zernio import ZernioProvider
    from hypogeum.agents.vertical_thumbnail import build_vertical_thumbnail_package

    provider = ZernioProvider()
    done = skipped = failed = 0

    for episode_id, channel_id, next_slot in targets:
        conn = get_connection(None)
        try:
            posts = _resolve_posts(conn, episode_id)
            title, topic = _episode_meta(conn, episode_id)
        finally:
            conn.close()

        tag = f"{episode_id} [{channel_id}] slot={next_slot}"
        if not posts:
            print(f"  SKIP  {tag} — no Zernio post id"); skipped += 1; continue

        stale = []  # (post_id, platforms, deliverable_id, video_url, existing, cover_age)
        for post_id, platforms, deliverable_id in posts:
            ptag = f"{tag} {deliverable_id}"
            try:
                existing = provider.get_post(post_id).get("post") or {}
            except Exception as exc:  # noqa: BLE001
                print(f"  FAIL  {ptag} — get_post: {exc}"); failed += 1; continue

            if (existing.get("status") or "").lower() == "published":
                print(f"  SKIP  {ptag} — already published, never touch a live post"); continue
            media_items = existing.get("mediaItems") or []
            has_video = bool(media_items and media_items[0].get("url"))
            thumb = media_items[0].get("thumbnail") if media_items else None
            if not has_video:
                print(f"  SKIP  {ptag} — post has no video mediaItem"); continue
            if not thumb:
                print(f"  SKIP  {ptag} — no cover at all yet (use backfill_vertical_covers.py)"); continue
            gen_at = _cover_generated_at(thumb)
            if gen_at is None:
                print(f"  SKIP  {ptag} — cover timestamp unparseable, leaving alone"); continue
            if not (_FEATURE_START <= gen_at < _FIX_LANDED):
                print(f"  SKIP  {ptag} — cover generated {gen_at.isoformat()}, already post-fix"); continue

            stale.append((post_id, platforms, deliverable_id, media_items[0]["url"], existing, gen_at))

        if not stale:
            skipped += 1; continue

        if not execute:
            for post_id, platforms, deliverable_id, _v, _e, gen_at in stale:
                print(f"  PLAN  {tag} -> post {post_id} ({deliverable_id}), stale cover from {gen_at.isoformat()}")
            done += 1
            continue

        with tempfile.TemporaryDirectory(prefix=f"vtcover_regen_{episode_id}_") as td:
            work = Path(td)
            if not _synth_concept_brief(episode_id, channel_id, title, topic, work, config):
                print(f"  FAIL  {tag} — could not synthesise a concept brief"); failed += 1; continue
            pkg = build_vertical_thumbnail_package(
                episode_id=episode_id, output_dir=work, config=config,
                channel_id=channel_id, log=log, authorize_via_channel=False,
            )
            if not pkg.get("generation_metadata", {}).get("vertical_cover"):
                print(f"  FAIL  {tag} — vertical builder fell back to the stub"); failed += 1; continue

            asset_id = pkg["main_thumbnail"]["asset_id"]
            cover_path = None
            for suf in (".png", ".jpg", ".jpeg", ".webp"):
                p = work / f"{Path(asset_id).name}{suf}"
                if p.exists():
                    cover_path = p; break
                p2 = work / "thumbnails" / f"{Path(asset_id).name}{suf}"
                if p2.exists():
                    cover_path = p2; break
            if cover_path is None:
                print(f"  FAIL  {tag} — cover file not found for {asset_id}"); failed += 1; continue

            try:
                cover_url = _stage_cover(cover_path, channel_id, episode_id, None)
            except Exception as exc:  # noqa: BLE001
                print(f"  FAIL  {tag} — staging: {exc}"); failed += 1; continue

            for post_id, platforms, deliverable_id, video_url, existing, gen_at in stale:
                ptag = f"{tag} {deliverable_id}"
                dtype = "main_episode" if deliverable_id == "main_episode" else "short"
                media_ref = MediaReference(
                    url=video_url, media_type="video", thumbnail_url=cover_url,
                    title=existing.get("title") or title,
                )
                plat_settings = {"tiktok": {"video_cover_image_url": cover_url}} if "tiktok" in platforms else None
                plat_specific = {"instagram": {"instagramThumbnail": cover_url}} if "instagram" in platforms else None

                try:
                    results = provider.repair_existing_post(
                        post_id,
                        channel_id=channel_id, deliverable_id=deliverable_id,
                        episode_id=episode_id, deliverable_type=dtype,
                        platforms=platforms,
                        media=[media_ref],
                        title=existing.get("title") or title,
                        content=existing.get("content") or existing.get("caption") or (topic or title),
                        platform_settings=plat_settings,
                        platform_specific_data=plat_specific,
                        db_path=None,
                    )
                except Exception as exc:  # noqa: BLE001
                    print(f"  FAIL  {ptag} — repair_existing_post: {exc}"); failed += 1; continue

                statuses = {p: r.get("status") for p, r in (results or {}).items()}
                print(f"  DONE  {ptag} — replaced stale cover (was {gen_at.isoformat()}); PUT result {statuses}")
                done += 1

    print(f"\n{done} done · {skipped} skipped · {failed} failed")
    return 0 if failed == 0 else 1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--execute", action="store_true")
    ap.add_argument("--episode", default=None)
    args = ap.parse_args()
    return run(execute=args.execute, only_episode=args.episode)


if __name__ == "__main__":
    raise SystemExit(main())
